//! `kb_core::add` — unified add primitive with atomic batched expire+upsert.
//!
//! # Contract
//!
//! This module is the SINGLE entry point for all "add an entry" operations:
//! - CLI: `src/commands/add.rs::Add::execute_with`
//! - MCP: `src/commands/mcp.rs::handle_add`
//! - MCP audit-record expire arm: `src/commands/mcp.rs::handle_audit_record`
//!
//! # JSONL-first ordering (Phase-5 ADR §Scenario 4)
//!
//! DB writes NEVER precede their event append.  The batch ordering is:
//!   1. `events::append_events_batch([expire_0, ..., expire_n, upsert, ev_add_0, ...])` — all at once
//!   2. `db::apply_event` for each event in the same order, all under the held flock.
//!
//! A crash between (1) and (2) leaves the JSONL ahead of the DB — the rebuild
//! path recovers.  A crash INSIDE (1) (before the write returns) is an atomic
//! append failure; the JSONL is unchanged and the DB is unchanged.  Either way
//! the steady-state invariant `DB == Materialize(events.jsonl)` holds.
//!
//! # Drift table (previously-divergent fields — now unified)
//!
//! | Field             | Old add.rs          | Old handle_add      | Old handle_audit_record | Unified here |
//! |-------------------|---------------------|---------------------|-------------------------|--------------|
//! | `kind` default    | `"belief"` (clap)   | `"belief"` (unwrap) | N/A (expire only)       | `"belief"`   |
//! | `session` field   | `"cli"` fallback    | `"mcp"` hard-coded  | `"mcp"` hard-coded      | caller sets  |
//! | `session_id` field| absent              | present if set      | N/A                     | passed in    |
//! | replace_path reason| `"replaced by --replace-path"` | `"replaced by MCP kb_add replace_path"` | N/A | caller sets via `expire_reason` |
//! | batch atomicity   | PER-LOOP append+apply | PER-LOOP append+apply | PER-LOOP append+apply | single batch |
//!
//! # TLA+ spec
//!
//! See `.state/agent-kb/tla/InnerGap.tla` and
//! `.state/agent-kb/tla/CrossBatch.tla` — two refinement layers:
//!   Layer 1 (inner): per-event append/apply gap within a single `kb_core::add` call.
//!   Layer 2 (cross-batch): cross-invocation boundary between distinct `kb_core::add` calls.

