    /// AC2: replace_path=true with two pre-existing entries:
    /// All events (2 expire + 1 upsert) appear in the JSONL in the correct order.
    #[test]
    fn test_kb_core_add_batch_atomicity_replace_path() {
        let (_dir, paths) = setup();
        let emb = NoopEmbedder;

        // Seed two existing entries at the same path.
        for seed_id in &["seed-1", "seed-2"] {
            let ev = serde_json::json!({
                "action": "upsert", "table": "entries",
                "id": seed_id, "path": "docs/guide",
                "summary": "old", "content": "old", "tags": [],
                "ts": "2024-01-01T00:00:00Z",
            });
            ev_mod::append_event(&paths.events, &ev).unwrap();
            let conn = db::open_db(&paths.db).unwrap();
            db::apply_event(&conn, &emb, &ev).unwrap();
        }

        // Count lines before.
        let before_lines = ev_mod::read_events(&paths.events).unwrap().events.len();
        assert_eq!(before_lines, 2, "seeded 2 events");

        let args = AddArgs {
            id: "new-1".to_string(),
            path: "docs/guide".to_string(),
            summary: "new guide".to_string(),
            content: "new content".to_string(),
            tags: serde_json::json!([]),
            version_ref: Some("abc".to_string()),
            permanent: false,
            replace_path: true,
            kind: "convention".to_string(),
            evidence_status: "n/a".to_string(),
            evidence_rows: vec![],
            ts: chrono::Utc::now().to_rfc3339(),
            session: "test".to_string(),
            session_id: None,
            expire_reason: "replaced by --replace-path".to_string(),
            dedup_cutoff: None,
            cues: vec![],
        };

        add(&paths, &emb, args).unwrap();

        let lines = ev_mod::read_events(&paths.events).unwrap().events;

        // 2 seed events + 2 expire + 1 upsert = 5 total events.
        assert_eq!(
            lines.len(),
            5,
            "expected 5 events (2 seed + 2 expire + 1 upsert), got {}",
            lines.len()
        );

        // Events 2 and 3 (0-indexed) must be expire events.
        let ev2 = &lines[2];
        let ev3 = &lines[3];
        let ev4 = &lines[4];
        assert_eq!(ev2["action"], "expire", "event[2] must be expire");
        assert_eq!(ev3["action"], "expire", "event[3] must be expire");
        assert_eq!(ev4["action"], "upsert", "event[4] must be upsert");
        assert_eq!(ev4["id"], "new-1");

        // DB: old entries must be stale, new entry active.
        let conn = Connection::open(&paths.db).unwrap();
        for seed_id in &["seed-1", "seed-2"] {
            let stale: i64 = conn
                .query_row(
                    "SELECT is_stale FROM entries WHERE id=?1",
                    params![seed_id],
                    |r| r.get(0),
                )
                .unwrap();
            assert_eq!(stale, 1, "seed {seed_id} must be stale");
        }
        let new_stale: i64 = conn
            .query_row("SELECT is_stale FROM entries WHERE id='new-1'", [], |r| {
                r.get(0)
            })
            .unwrap();
        assert_eq!(new_stale, 0, "new entry must be active");
    }

