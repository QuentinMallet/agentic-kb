// Thread-local, not a global static: memoization happens per-add on one
// thread, and cargo runs tests in parallel threads, so a global counter
// picks up concurrent tests' resolutions inside this test's window
// (cross-test race, found when the storage-reliability tests shifted
// scheduling). A thread-local counter measures only this test's own calls.
#[cfg(test)]
thread_local! {
    static CITATION_HASH_RESOLUTION_CALLS: Cell<usize> = const { Cell::new(0) };
}

fn resolve_citation_hash(
    repo_root: &std::path::Path,
    file_rel: &str,
    range: Option<(usize, usize)>,
) -> Result<String> {
    #[cfg(test)]
    CITATION_HASH_RESOLUTION_CALLS.with(|c| c.set(c.get() + 1));

    compute_citation_hash(repo_root, file_rel, range)
}

/// Input arguments for `kb_core::add`.
///
/// Caller is responsible for:
/// - validating `kind`, `tags`, `evidence_rows` via `validate_kb_add_inputs`
/// - computing `evidence_status` via `compute_evidence_status_write`
/// - constructing `id` (UUID or caller-supplied)
/// - setting `session` and `session_id` appropriate to the call site
/// - setting `expire_reason` appropriate to the call site
pub struct AddArgs {
    pub id: String,
    pub path: String,
    pub summary: String,
    pub content: String,
    /// JSON array value of tags.
    pub tags: Value,
    pub version_ref: Option<String>,
    pub permanent: bool,
    pub replace_path: bool,
    pub kind: String,
    pub evidence_status: String,
    pub evidence_rows: Vec<Value>,
    /// Timestamp string (RFC 3339).
    pub ts: String,
    /// Session label written into the event `"session"` field (e.g. `"cli"` or `"mcp"`).
    pub session: String,
    /// Session ID written into the upsert event `"session_id"` field.
    /// `None` means the field is omitted from the event (backward-compatible).
    pub session_id: Option<String>,
    /// Reason string used in expire events generated by `replace_path`.
    /// Preserves per-call-site wording (previously divergent across call sites).
    pub expire_reason: String,
    /// Cosine cutoff for the near-duplicate probe. `None` disables the probe
    /// (internal callers: rebuild, digest, compress — re-adding known content).
    pub dedup_cutoff: Option<f32>,
    /// Cue anchors: agent-supplied semantic entry points, pattern
    /// "[Main Entity] + [Key Aspect]" (Memora). Ride the upsert event and are
    /// stored as embedded rows in the `cues` table. Empty = no cues field.
    pub cues: Vec<String>,
}

/// A live entry semantically close to the one being added.
#[derive(Debug, Clone, serde::Serialize)]
pub struct SimilarEntry {
    pub id: String,
    pub path: String,
    pub summary: String,
    pub score: f32,
}

/// Result returned by `kb_core::add`.
#[derive(Debug)]
pub struct AddOutcome {
    /// The entry ID (same as `AddArgs::id`).
    pub entry_id: String,
    /// Live entries with embedding cosine >= `dedup_cutoff` (empty when the
    /// probe is disabled). The add is NOT blocked — the calling agent decides
    /// whether to merge, expire, or keep both.
    pub similar_existing: Vec<SimilarEntry>,
}

/// Unified add primitive: acquires the write lock, opens for mutation, and
/// delegates to [`add_locked`].
///
/// A thin wrapper on purpose. Callers that already hold the lock — a locked
/// batch import, any future multi-entry write path — must call [`add_locked`]
/// directly; calling this one would re-acquire the flock and, before the
/// re-entrancy registry existed, deadlock on itself (ADR-1).
///
/// INVARIANT: this function NEVER reads `KB_NO_EMBED` from the environment.
/// The caller must construct the Embedder before calling and pass it by reference.
pub fn add(
    paths: &config::Paths,
    embedder: &dyn embedder::Embedder,
    args: AddArgs,
) -> Result<AddOutcome> {
    let lock = acquire_lock(&paths.lock)?;
    let conn = db::open_rw(paths, &lock)?;
    add_locked(&lock, &conn, paths, embedder, args)
}

/// The add logic, for a caller that already holds this repository's write lock.
///
/// 1. Validates, redacts, and caps the inputs.
/// 2. Collects any existing non-stale entry IDs at `args.path` (when `replace_path=true`).
/// 3. Builds expire events + the upsert event + evidence-add events.
/// 4. Appends ALL events in ONE `events::append_events_batch` call (JSONL-first).
/// 5. Applies each event to the DB in order, all under the caller's flock.
///
/// Input preparation runs inside the critical section rather than ahead of it,
/// which is a deliberate trade: one code path for both entry points is worth
/// more than the few milliseconds of citation hashing it adds to the lock hold.
///
/// `lock` is proof, not a resource: it is checked against `paths.lock` and never
/// released here — the caller's guard still owns it.
pub fn add_locked(
    lock: &Lock,
    conn: &Connection,
    paths: &config::Paths,
    embedder: &dyn embedder::Embedder,
    mut args: AddArgs,
) -> Result<AddOutcome> {
    // Redundant but intentional: open_rw canonicalized paths.lock before it
    // opened `conn`; re-checking here keeps add_locked self-contained for any
    // future caller handed a live lock + connection pair from elsewhere.
    let expected_lock = std::fs::canonicalize(&paths.lock).with_context(|| {
        format!(
            "canonicalize write lock {} (add_locked requires a live lock guard)",
            paths.lock.display()
        )
    })?;
    if lock.path() != expected_lock {
        anyhow::bail!(
            "add_locked: the supplied lock guards {}, but this repository's write lock is {}",
            lock.path().display(),
            expected_lock.display()
        );
    }

    let repo_root = paths
        .db
        .parent()
        .and_then(|p| p.parent())
        .and_then(|p| p.parent())
        .ok_or_else(|| anyhow::anyhow!("cannot determine repository root from KB database path"))?;

    // Normalize path-only evidence before constructing any events. Explicit
    // assertions are authoritative and are never replaced, even when wrong.
    let mut resolved_hashes_by_path: HashMap<String, String> = HashMap::new();
    for evidence in &mut args.evidence_rows {
        let hash_missing = evidence
            .get("citation_hash")
            .and_then(Value::as_str)
            .map(str::is_empty)
            .unwrap_or(true);
        if !hash_missing {
            continue;
        }
        let citation_path = evidence
            .get("citation_path")
            .and_then(Value::as_str)
            .filter(|path| !path.is_empty())
            .ok_or_else(|| {
                anyhow::anyhow!("evidence row missing required citation_path or citation_hash")
            })?;
        let (file_rel, range) = parse_citation_path(citation_path)
            .map_err(|error| anyhow::anyhow!("resolve citation_path {citation_path:?}: {error}"))?;
        let citation_hash = if let Some(existing) = resolved_hashes_by_path.get(citation_path) {
            existing.clone()
        } else {
            let resolved = resolve_citation_hash(repo_root, file_rel, range).map_err(|error| {
                anyhow::anyhow!("resolve citation_path {citation_path:?}: {error}")
            })?;
            resolved_hashes_by_path.insert(citation_path.to_string(), resolved.clone());
            resolved
        };
        let object = evidence
            .as_object_mut()
            .ok_or_else(|| anyhow::anyhow!("evidence row must be a JSON object"))?;
        object.insert("citation_hash".to_string(), Value::String(citation_hash));
        if object.get("citation_sha").map_or(true, Value::is_null) {
            if let Some(head) = config::git_head_sha() {
                object.insert("citation_sha".to_string(), Value::String(head));
            }
        }
    }

    // Resource caps for cue anchors (mirrors evidence-row caps): bounded count
    // and length keep the embed cost and cue-table growth per add bounded.
    const MAX_CUES: usize = 8;
    const MAX_CUE_CHARS: usize = 120;
    if args.cues.len() > MAX_CUES {
        anyhow::bail!("too many cues: {} (max {MAX_CUES})", args.cues.len());
    }
    if args.cues.iter().any(|c| c.chars().count() > MAX_CUE_CHARS) {
        anyhow::bail!("cue exceeds {MAX_CUE_CHARS} chars");
    }

    // Redact credentials from user-supplied text fields before persisting.
    args.content = redactor::redact_str(&args.content).into_owned();
    args.summary = redactor::redact_str(&args.summary).into_owned();
    for cue in args.cues.iter_mut() {
        *cue = redactor::redact_str(cue).into_owned();
    }
    redactor::redact_in_place(&mut args.tags);
    for ev in args.evidence_rows.iter_mut() {
        if let Some(excerpt) = ev.get_mut("citation_excerpt") {
            redactor::redact_in_place(excerpt);
        }
    }

    // Entry field caps — validated on the REDACTED values (redaction markers
    // can change length) so the schema CHECK can never fire mid-batch.
    // Rejecting here gives a clear error; apply_event's clamp is for legacy
    // pre-cap events only, never for new writes.
    if args.summary.chars().count() > db::MAX_SUMMARY_CHARS {
        anyhow::bail!(
            "summary exceeds {} chars ({})",
            db::MAX_SUMMARY_CHARS,
            args.summary.chars().count()
        );
    }
    if args.content.chars().count() > db::MAX_ENTRY_CONTENT_CHARS {
        anyhow::bail!(
            "content exceeds {} chars ({}) — split the entry or use kb ingest",
            db::MAX_ENTRY_CONTENT_CHARS,
            args.content.chars().count()
        );
    }

    // Near-duplicate probe (Memora pickup .5): semantic-only search for live
    // entries close to the incoming one. Runs BEFORE the new entry is written
    // so it can never self-match. Best-effort: a probe failure must not block
    // the add.
    let similar_existing: Vec<SimilarEntry> = match args.dedup_cutoff {
        Some(cutoff) if !embedder.is_noop() => {
            let probe_text = db::entry_embed_text(
                db::EmbedTextMode::from_env(),
                &args.path,
                &args.summary,
                &args.content,
                &args.tags.to_string(),
            );
            let opts = db::SearchOptions {
                limit: 5,
                do_fts: false,
                do_semantic: true,
                path_prefix: None,
                tag_filter: None,
                inline_verify_k: 0,
                repo_root: None,
                verify_pool_size: None,
                recency_lambda: 0.0,
                mmr_lambda: 0.0,
            };
            match db::search_entries(&conn, embedder, &probe_text, &opts) {
                Ok(results) => results
                    .into_iter()
                    .filter(|r| r.score >= cutoff)
                    .filter(|r| r.id != args.id)
                    // replace_path expires same-path entries in this very call —
                    // reporting them as duplicates would be noise.
                    .filter(|r| !(args.replace_path && r.path == args.path))
                    .map(|r| SimilarEntry {
                        id: r.id,
                        path: r.path,
                        summary: r.summary,
                        score: r.score,
                    })
                    .collect(),
                Err(e) => {
                    eprintln!("warn: dedup probe failed (add proceeds): {e}");
                    vec![]
                }
            }
        }
        _ => vec![],
    };

    // Collect existing IDs to expire when replace_path is requested.
    let existing_ids: Vec<String> = if args.replace_path {
        let mut stmt = conn.prepare("SELECT id FROM entries WHERE path=?1 AND is_stale=0")?;
        let ids = stmt
            .query_map(params![args.path], |r| r.get(0))?
            .collect::<rusqlite::Result<Vec<String>>>()?;
        ids
    } else {
        vec![]
    };

    // Build expire events (one per existing entry being replaced).
    let expire_events: Vec<Value> = existing_ids
        .iter()
        .map(|old_id| {
            serde_json::json!({
                "action": "expire",
                "table": "entries",
                "id": old_id,
                "reason": args.expire_reason,
                "ts": args.ts,
                "session": args.session,
            })
        })
        .collect();

    // Build the upsert event. Cues ride the upsert event itself — there are
    // no separate cue events in the JSONL (.state/agent-kb/tla/CueBatch.tla).
    let mut add_event = serde_json::json!({
        "action": "upsert",
        "table": "entries",
        "id": args.id,
        "path": args.path,
        "summary": args.summary,
        "content": args.content,
        "tags": args.tags,
        "version_ref": args.version_ref,
        "permanent": args.permanent,
        "kind": args.kind,
        "evidence_status": args.evidence_status,
        "session_id": args.session_id,
        "ts": args.ts,
        "session": args.session,
    });
    if !args.cues.is_empty() {
        add_event["cues"] = serde_json::json!(args.cues);
    }

    // Build evidence-add events (one per evidence row).
    let evidence_events: Vec<Value> = args
        .evidence_rows
        .iter()
        .map(|ev| {
            let evidence = Evidence {
                id: uuid::Uuid::new_v4().to_string(),
                entry_id: args.id.clone(),
                kind: ev
                    .get("kind")
                    .and_then(|v| v.as_str())
                    .unwrap_or("code")
                    .to_string(),
                citation_path: ev
                    .get("citation_path")
                    .and_then(|v| v.as_str())
                    .map(|s| s.to_string()),
                citation_sha: ev
                    .get("citation_sha")
                    .and_then(|v| v.as_str())
                    .map(|s| s.to_string()),
                citation_hash: ev
                    .get("citation_hash")
                    .and_then(|v| v.as_str())
                    .unwrap_or("")
                    .to_string(),
                citation_excerpt: ev
                    .get("citation_excerpt")
                    .and_then(|v| v.as_str())
                    .map(|s| s.to_string()),
                derived_from: ev
                    .get("derived_from")
                    .and_then(|v| v.as_str())
                    .map(|s| s.to_string()),
                recorded_at: Some(args.ts.clone()),
            };
            events::evidence_add_event(&args.id, &evidence, args.version_ref.as_deref())
        })
        .collect();

    // ATOMIC BATCH: all expire events + upsert + evidence-add events in ONE write.
    // JSONL-first invariant: this append precedes all DB writes.
    // Order: expires, upsert, evidence-adds. The same Vec is then applied to the
    // DB in-order under the held flock, so no per-event clone is needed.
    let mut batch: Vec<Value> = expire_events;
    batch.push(add_event);
    batch.extend(evidence_events);
    events::append_events_batch(&paths.events, &batch)?;
    kill_point(KillPoint::AfterLogBatch);

    for ev in &batch {
        db::apply_event(&conn, embedder, ev)?;
    }

    if args.evidence_status == "missing"
        && matches!(args.kind.as_str(), "observation" | "belief" | "procedure")
    {
        eprintln!(
            "kb: warning: kind='{}' entry stored with evidence_status=missing — attach evidence via citation_path (server resolves sha/hash) or kb cite",
            args.kind
        );
    }

    Ok(AddOutcome {
        entry_id: args.id,
        similar_existing,
    })
}

