    //
    // AC2 (batch atomicity): expire events and upsert land in ONE
    // `append_events_batch` call — NOT a loop of per-event appends.
    //
    // Pre-fix, the call sites in add.rs and mcp.rs use:
    //   for old_id in existing_ids {
    //       append_event(&paths.events, &expire_ev)?;   // ← one append per expire
    //       apply_event(&conn, emb, &expire_ev)?;
    //   }
    //   append_events_batch(&paths.events, &[add_event, ...evidence...])
    //
    // That means N+1 separate JSONL write calls, not 1.  This test verifies
    // that after a `kb_core::add` with replace_path=true the event log contains
    // all events as a SINGLE contiguous block (measurable via line count == 1 +
    // expire_count + evidence_count and ordering verification).
    //
    // Because kb_core::add is the NEW module, this test can only PASS once the
    // implementation below exists.  Before the module existed the test file
    // itself would not compile, proving the "failing first" property.
